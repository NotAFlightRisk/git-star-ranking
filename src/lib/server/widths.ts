// the size each table was measured at
const FONTS = {
  verdana: { size: 11, widths: VERDANA },
  'verdana bold': { size: 10, widths: VERDANA_BOLD },
  'helvetica bold': { size: 11, widths: HELVETICA_BOLD }
};

export type Font = keyof typeof FONTS;

const M = 'm'.charCodeAt(0) - 32;

/** How wide text sets, counting anything past ASCII as an m */
export function widthOf(text: string, font: Font, size = FONTS[font].size) {
  const { widths, size: measured } = FONTS[font];
  let width = 0;
  for (const char of text) width += widths[char.codePointAt(0)! - 32] ?? widths[M];
  return (width * size) / measured;
}
